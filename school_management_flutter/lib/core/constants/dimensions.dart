  // Utility methods
  static double getResponsiveSpacing(BuildContext context) {
    final width = MediaQuery.of(context).size.width;
    if (width < screenS) return spacingS;
    if (width < screenM) return spacingM;
    if (width < screenL) return spacingL;
    return spacingXL;
  }

  static double getResponsivePadding(BuildContext context) {
    final width = MediaQuery.of(context).size.width;
    if (width < screenS) return paddingS;
    if (width < screenM) return paddingM;
    if (width < screenL) return paddingL;
    return paddingXL;
  }

  static double getResponsiveFontSize(BuildContext context, double baseSize) {
    final width = MediaQuery.of(context).size.width;
    double scale = 1.0;

    if (width < screenS) scale = 0.8;
    else if (width < screenM) scale = 0.9;
    else if (width < screenL) scale = 1.0;
    else if (width < screenXL) scale = 1.1;
    else scale = 1.2;

    return baseSize * scale;
  }

  static double getResponsiveIconSize(BuildContext context, double baseSize) {
    final width = MediaQuery.of(context).size.width;
    double scale = 1.0;

    if (width < screenS) scale = 0.8;
    else if (width < screenM) scale = 0.9;
    else if (width < screenL) scale = 1.0;
    else if (width < screenXL) scale = 1.1;
    else scale = 1.2;

    return baseSize * scale;
  }

  static bool isMobile(BuildContext context) {
    return MediaQuery.of(context).size.width < screenM;
  }

  static bool isTablet(BuildContext context) {
    final width = MediaQuery.of(context).size.width;
    return width >= screenM && width < screenL;
  }

  static bool isDesktop(BuildContext context) {
    return MediaQuery.of(context).size.width >= screenL;
  }
}